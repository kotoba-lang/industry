use clap::{Parser, Subcommand};
use kotoba_compiler::Compiler;
use std::fs;

/// `kotoba`言語のコンパイラ
#[derive(Parser)]
#[command(name = "kotoba")]
#[command(about = "A compiler for the kotoba language", long_about = None)]
struct Cli {
    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand)]
enum Commands {
    /// Compiles a kotoba file
    Compile {
        /// The path to the kotoba file to compile
        path: std::path::PathBuf,
        /// Output file path
        #[arg(short, long)]
        output: Option<std::path::PathBuf>,
    },
}

fn main() {
    let cli = Cli::parse();

    match &cli.command {
        Commands::Compile { path, output } => {
            let source_code = match fs::read_to_string(path) {
                Ok(code) => code,
                Err(e) => {
                    eprintln!("ファイル読み込みエラー {}: {}", path.display(), e);
                    return;
                }
            };

            let program = match kotoba_parser::parse_program(&source_code) {
                Ok(statements) => statements,
                Err(e) => {
                    eprintln!("構文解析エラー: {:?}", e);
                    return;
                }
            };

            let mut compiler = Compiler::new();
            match compiler.compile(program) {
                Ok(rust_code) => {
                    let output_content = format!(
                        "// Generated by kotoba compiler from: {}\n\nuse kotoba_core;\n\n{}",
                        path.display(),
                        rust_code
                    );
                    if let Some(output_path) = output {
                        if let Err(e) = fs::write(output_path, output_content) {
                            eprintln!("ファイル書き込みエラー {}: {}", output_path.display(), e);
                        }
                    } else {
                        println!("{}", output_content);
                    }
                }
                Err(e) => {
                    eprintln!("コンパイルエラー: {}", e);
                }
            }
        }
    }
}
